export function classifyFactoryBrief(brief = '') {
  const b = String(brief || '').toLowerCase();
  const hasMedia =
    /music video|song|track|shot plan|cathedral|cinema|video|lyric|chorus|bpm|director|film|visual|check the source|awakening/i.test(
      b
    );
  const hasSoftware =
    /software|app|wasm|portal|code|github|tracker|ant farm|gnn|connectome|dashboard|scraper|osint|build me a|compile|deploy/i.test(
      b
    );
  if (hasMedia && hasSoftware) return 'hybrid_flagship';
  if (hasSoftware && !hasMedia) return 'software_product';
  return 'music_video';
}

